#!/usr/bin/env python3
"""Shared learnings: turn a scout's LEARNING PROPOSAL block into a file, review it, index the folder.

  python3 scripts/learnings.py propose [BLOCK_FILE | -] [--author HANDLE] [--pr] [--allow-dollars]
  python3 scripts/learnings.py review ID (--accept | --decline | --trial) --note "why" [--trades N] [--review-by DATE]
  python3 scripts/learnings.py index

propose reads the block the Sunday scout printed (a file, or stdin with "-"), checks the required
fields and the privacy rule (no 9-digit numbers, which is what account identifiers look like), writes learnings/proposed/<id>.md,
rebuilds learnings/INDEX.md and, with --pr, branches, commits, pushes and opens the pull request with gh.
review moves a learning between folders and records the maintainer's decision. index rebuilds INDEX.md.
No network, no brokerage, no Dropbox: this script only touches this repo.
"""
import argparse, datetime, glob, os, re, subprocess, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.join(REPO, "learnings")
FOLDERS = ("proposed", "accepted", "declined")
AREAS = ("entry", "exit", "sizing", "regime", "flags", "scheduling", "tooling", "reporting")
DIRECTIONS = ("tightening", "loosening", "neutral")
REQUIRED = ("title", "area", "direction", "pattern", "evidence", "mechanism", "change", "cost", "judge")
ALIASES = {
    "proposed_change": "change", "expected_cost": "cost", "how_to_judge": "judge",
    "rule": "rule_touched", "review": "review_by", "status": "status_at_source",
    "source": "status_at_source", "trades_n": "trades",
}
ACCOUNT_RE = re.compile(r"\b\d{9}\b")
DOLLAR_RE = re.compile(r"\$\s?\d")
TODAY = datetime.date.today().isoformat()


def die(msg):
    sys.exit("learnings.py: " + msg)


def parse_block(text):
    """key: value lines; continuation lines append to the open key."""
    fields, key = {}, None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.upper().startswith("LEARNING PROPOSAL"):
            continue
        m = re.match(r"^([A-Za-z][A-Za-z _/-]{0,40}):\s*(.*)$", line)
        if m:
            key = re.sub(r"[ /-]+", "_", m.group(1).strip().lower())
            key = ALIASES.get(key, key)
            fields[key] = m.group(2).strip()
        elif key:
            fields[key] = (fields[key] + " " + line).strip()
    return fields


def privacy_check(text, allow_dollars):
    if ACCOUNT_RE.search(text):
        die("a 9-digit number is in the block; that is what account numbers look like. Remove it.")
    # Dollar figures are allowed since 2026-11-24 (Ken): amounts, wins and losses are community data.


def slugify(s, n=40):
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s[:n].rstrip("-") or "learning"


def default_author():
    try:
        out = subprocess.run(["gh", "api", "user", "-q", ".login"], capture_output=True, text=True, timeout=8)
        if out.returncode == 0 and out.stdout.strip():
            return slugify(out.stdout.strip(), 24)
    except Exception:
        pass
    try:
        name = subprocess.run(["git", "config", "user.name"], capture_output=True, text=True, cwd=REPO).stdout.strip()
        if name:
            return slugify(name, 24)
    except Exception:
        pass
    return "anon"


def read_frontmatter(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    fm = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                fm[k.strip()] = v.strip()
    return fm, text


def write_index():
    rows = []
    for folder in FOLDERS:
        for p in glob.glob(os.path.join(ROOT, folder, "*.md")):
            fm, _ = read_frontmatter(p)
            if "id" not in fm:
                continue
            rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
            rows.append((fm.get("date", ""), fm))
            fm["_rel"] = rel
    rows.sort(key=lambda r: r[0], reverse=True)
    lines = [
        "# Learnings index", "",
        "Generated by `python3 scripts/learnings.py index` on " + TODAY + ". Do not edit by hand.", "",
        "| Date | Id | Author | Area | Direction | Status | Trades | Review by | Title |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for _, fm in rows:
        lines.append("| {date} | [{id}]({rel}) | {author} | {area} | {direction} | {status} | {trades} | {review_by} | {title} |".format(
            date=fm.get("date", ""), id=fm.get("id", ""), rel=fm["_rel"], author=fm.get("author", ""),
            area=fm.get("area", ""), direction=fm.get("direction", ""), status=fm.get("status", ""),
            trades=fm.get("trades", ""), review_by=fm.get("review_by", ""), title=fm.get("title", "")))
    if not rows:
        lines.append("| | | | | | | | | (none yet) |")
    counts = {f: len(glob.glob(os.path.join(ROOT, f, "*.md"))) for f in FOLDERS}
    lines += ["", "Counts: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + "."]
    open(os.path.join(ROOT, "INDEX.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return len(rows)


def cmd_propose(a):
    text = sys.stdin.read() if a.block in (None, "-") else open(a.block, encoding="utf-8").read()
    f = parse_block(text)
    missing = [k for k in REQUIRED if not f.get(k)]
    if missing:
        die("block is missing: " + ", ".join(missing) + ". The fields are listed in learnings/TEMPLATE.md.")
    if f["area"] not in AREAS:
        die("area must be one of " + ", ".join(AREAS))
    if f["direction"] not in DIRECTIONS:
        die("direction must be one of " + ", ".join(DIRECTIONS))
    privacy_check(text, a.allow_dollars)
    author = a.author or default_author()
    date = f.get("date") or TODAY
    lid = f.get("id") or f"{date}-{author}-{slugify(f['title'])}"
    path = os.path.join(ROOT, "proposed", lid + ".md")
    if os.path.exists(path):
        die("already exists: " + path)
    trades = re.search(r"\d+", f.get("trades", "") or f.get("evidence", "")) 
    trades = trades.group(0) if trades else "0"
    fm = "\n".join([
        "---", f"id: {lid}", f"date: {date}", f"author: {author}", f"area: {f['area']}",
        f"direction: {f['direction']}", "status: proposed", f"trades: {trades}",
        f"review_by: {f.get('review_by', '')}", f"rule_touched: {f.get('rule_touched', 'new')}",
        f"title: {f['title']}", "---", ""])
    body = "\n".join([
        f"# {f['title']}", "",
        "## Pattern", f["pattern"], "", "## Evidence", f["evidence"], "", "## Mechanism", f["mechanism"], "",
        "## Proposed change", f["change"], "", "## Expected cost", f["cost"], "", "## How to judge", f["judge"], "",
        "## Source", f"Status at source: {f.get('status_at_source', 'proposed to operator')}. Operator: {author}. Emitted by the Sunday scout on {date}.", "",
        "## Decision", "(maintainer fills this in)", ""])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(fm + body)
    write_index()
    rel = os.path.relpath(path, REPO)
    print("wrote", rel)
    if a.pr:
        open_pr(lid, f["title"], rel)
    else:
        print("next: review the file, then `python3 scripts/learnings.py propose --pr` style push, or commit and open a pull request by hand (CONTRIBUTING.md).")


def run(cmd, check=True):
    print("$", " ".join(cmd))
    r = subprocess.run(cmd, cwd=REPO, text=True)
    if check and r.returncode != 0:
        die("command failed: " + " ".join(cmd))
    return r.returncode


def open_pr(lid, title, rel):
    branch = "learning/" + lid
    run(["git", "checkout", "-b", branch])
    run(["git", "add", rel, "learnings/INDEX.md"])
    run(["git", "commit", "-m", f"Learning: {title}\n\nProposed by the Sunday scout; see {rel}."])
    if run(["git", "push", "-u", "origin", branch], check=False) != 0:
        print("push failed. If you do not have write access, run `gh repo fork --remote` once, then `git push -u fork " + branch + "` and `gh pr create --fill`.")
        return
    body = (f"Learning proposal from an installed copy's Sunday scout. File: `{rel}`.\n\n"
            "Checklist: threshold met or marked idea; no account identifiers; one change, one area.\n")
    run(["gh", "pr", "create", "--base", "main", "--title", f"Learning: {title}", "--body", body], check=False)


def find(lid):
    for folder in FOLDERS:
        p = os.path.join(ROOT, folder, lid + ".md")
        if os.path.exists(p):
            return p
    die("no learning with id " + lid)


def cmd_review(a):
    path = find(a.id)
    status = "accepted" if a.accept else "declined" if a.decline else "trial"
    folder = "proposed" if status == "trial" else status
    fm, text = read_frontmatter(path)
    text = re.sub(r"^status: .*$", "status: " + status, text, count=1, flags=re.M)
    if a.trades is not None:
        text = re.sub(r"^trades: .*$", f"trades: {a.trades}", text, count=1, flags=re.M)
    if a.review_by:
        text = re.sub(r"^review_by: .*$", f"review_by: {a.review_by}", text, count=1, flags=re.M)
    line = f"{TODAY}, maintainer ({a.by or default_author()}): {status}. {a.note}"
    if "## Decision" in text:
        text = re.sub(r"(## Decision\n)(\(maintainer fills this in\)\n)?", r"\1" + line + "\n", text, count=1)
    else:
        text = text.rstrip("\n") + "\n\n## Decision\n" + line + "\n"
    new_path = os.path.join(ROOT, folder, os.path.basename(path))
    open(path, "w", encoding="utf-8").write(text)
    if new_path != path:
        subprocess.run(["git", "mv", path, new_path], cwd=REPO, capture_output=True)
        if os.path.exists(path):
            os.replace(path, new_path)
    write_index()
    print(status, os.path.relpath(new_path, REPO))
    if status == "accepted":
        print("now: fold it into rules/RULEBOOK.md with a [community] tag and add it to the next SKILL-UPDATE prompt.")


def cmd_index(a):
    n = write_index()
    print(f"indexed {n} learnings -> learnings/INDEX.md")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("propose"); p.add_argument("block", nargs="?"); p.add_argument("--author"); p.add_argument("--pr", action="store_true"); p.add_argument("--allow-dollars", action="store_true"); p.set_defaults(fn=cmd_propose)
    r = sub.add_parser("review"); r.add_argument("id"); g = r.add_mutually_exclusive_group(required=True)
    g.add_argument("--accept", action="store_true"); g.add_argument("--decline", action="store_true"); g.add_argument("--trial", action="store_true")
    r.add_argument("--note", required=True); r.add_argument("--trades", type=int); r.add_argument("--review-by"); r.add_argument("--by"); r.set_defaults(fn=cmd_review)
    i = sub.add_parser("index"); i.set_defaults(fn=cmd_index)
    a = ap.parse_args(); a.fn(a)


if __name__ == "__main__":
    main()
