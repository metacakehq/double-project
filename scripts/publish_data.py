#!/usr/bin/env python3
"""Community data: merge an operator's run records into data/<handle>/ and rebuild the scoreboard.

  python3 scripts/publish_data.py publish --handle HANDLE --source DIR [--pr]
  python3 scripts/publish_data.py scoreboard

publish reads every *-status.csv and *-trades.csv under DIR (the repo-records folder the runs write
to in the operator's store, same headers as data/README.md), merges them into data/HANDLE/status.csv
(key: date + run) and data/HANDLE/trades.csv (key: trade_id), newest record wins, rebuilds
data/SCOREBOARD.md and, with --pr, branches, commits, pushes and opens the pull request with gh.
scoreboard only rebuilds data/SCOREBOARD.md from every operator folder.
Refuses any 9-digit number anywhere in the records (account identifiers). No brokerage, no network otherwise.
"""
import argparse, csv, datetime, glob, io, os, re, subprocess, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(REPO, "data")
STATUS_COLS = "operator,date,run,v,hwm,floor,regime,cash,open_positions,actions,flags,notes".split(",")
TRADE_COLS = ("operator,trade_id,entry_date,exit_date,ticker,vehicle,side,shares,entry_price,exit_price,"
              "pnl_usd,pnl_pct,hold_sessions,setup,regime_entry,stop_atr,risk_pct_v,exit_type,notes").split(",")
ACCOUNT_RE = re.compile(r"\b\d{9}\b")
TODAY = datetime.date.today().isoformat()


def die(m):
    sys.exit("publish_data.py: " + m)


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def write_csv(path, cols, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({c: r.get(c, "") for c in cols})


def merge(existing, incoming, key, handle):
    by = {key(r): r for r in existing}
    for r in incoming:
        r["operator"] = handle
        by[key(r)] = {**by.get(key(r), {}), **{k: v for k, v in r.items() if v not in (None, "")}}
    return list(by.values())


def fnum(x):
    try:
        return float(str(x).replace(",", "").replace("$", ""))
    except Exception:
        return None


def cmd_publish(a):
    handle = re.sub(r"[^a-z0-9-]", "-", a.handle.lower()).strip("-")
    if not handle:
        die("handle is empty")
    src = os.path.expanduser(a.source)
    files = sorted(glob.glob(os.path.join(src, "**", "*.csv"), recursive=True))
    if not files:
        die("no csv files under " + src)
    st_in, tr_in = [], []
    for p in files:
        text = open(p, encoding="utf-8").read()
        if ACCOUNT_RE.search(text):
            die(f"{p} contains a 9-digit number; that is what account identifiers look like. Remove it.")
        rows = list(csv.DictReader(io.StringIO(text)))
        if p.endswith("-status.csv") or "status" in os.path.basename(p):
            st_in += rows
        elif p.endswith("-trades.csv") or "trade" in os.path.basename(p):
            tr_in += rows
    folder = os.path.join(DATA, handle)
    st = merge(read_csv(os.path.join(folder, "status.csv")), st_in, lambda r: (r.get("date", ""), r.get("run", "")), handle)
    tr = merge(read_csv(os.path.join(folder, "trades.csv")), tr_in, lambda r: r.get("trade_id", ""), handle)
    st.sort(key=lambda r: (r.get("date", ""), r.get("run", "")))
    tr.sort(key=lambda r: (r.get("exit_date", ""), r.get("trade_id", "")))
    write_csv(os.path.join(folder, "status.csv"), STATUS_COLS, st)
    write_csv(os.path.join(folder, "trades.csv"), TRADE_COLS, tr)
    print(f"data/{handle}: {len(st)} status rows, {len(tr)} trades ({len(st_in)} and {len(tr_in)} records read from {len(files)} files)")
    scoreboard()
    if a.pr:
        open_pr(handle)


def scoreboard():
    lines = ["# Community scoreboard", "",
             f"Generated by `python3 scripts/publish_data.py scoreboard` on {TODAY} from every `data/<handle>/` folder. Do not edit.", "",
             "| Operator | First run | Last run | Last V | Trades | Wins | Losses | Win rate | Net realized | Avg win | Avg loss | Payoff | Bear-fund trades |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    tot = dict(trades=0, wins=0, losses=0, net=0.0)
    for folder in sorted(glob.glob(os.path.join(DATA, "*", ""))):
        h = os.path.basename(os.path.dirname(folder))
        st, tr = read_csv(os.path.join(folder, "status.csv")), read_csv(os.path.join(folder, "trades.csv"))
        dates = sorted(r["date"] for r in st if r.get("date"))
        vs = [(r["date"], fnum(r.get("v"))) for r in st if fnum(r.get("v")) is not None]
        last_v = f"{vs[-1][1]:,.2f}" if vs else ""
        pnls = [fnum(r.get("pnl_usd")) for r in tr if fnum(r.get("pnl_usd")) is not None]
        wins = [p for p in pnls if p > 0]; losses = [p for p in pnls if p <= 0]
        net = sum(pnls)
        aw = sum(wins) / len(wins) if wins else 0; al = -sum(losses) / len(losses) if losses else 0
        payoff = f"{aw / al:.1f}" if al else ""
        wr = f"{len(wins) / len(pnls) * 100:.0f}%" if pnls else ""
        bear = sum(1 for r in tr if r.get("vehicle") == "bear_fund")
        lines.append(f"| {h} | {dates[0] if dates else ''} | {dates[-1] if dates else ''} | {last_v} | {len(pnls)} | {len(wins)} | {len(losses)} | {wr} | {net:+,.2f} | {aw:,.2f} | {al:,.2f} | {payoff} | {bear} |")
        tot["trades"] += len(pnls); tot["wins"] += len(wins); tot["losses"] += len(losses); tot["net"] += net
    lines += ["", f"All operators: {tot['trades']} trades, {tot['wins']} wins, {tot['losses']} losses, net realized {tot['net']:+,.2f} dollars.",
              "", "Figures are what each operator's runs recorded; nothing here is audited against a brokerage statement. A row with a blank Last V has status rows without account values."]
    open(os.path.join(DATA, "SCOREBOARD.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote data/SCOREBOARD.md")


def run(cmd, check=True):
    print("$", " ".join(cmd))
    r = subprocess.run(cmd, cwd=REPO, text=True)
    if check and r.returncode != 0:
        die("command failed: " + " ".join(cmd))
    return r.returncode


def open_pr(handle):
    branch = f"data/{handle}/{TODAY}"
    run(["git", "checkout", "-b", branch])
    run(["git", "add", f"data/{handle}", "data/SCOREBOARD.md"])
    run(["git", "commit", "-m", f"Data: {handle} through {TODAY}\n\nRun records published with scripts/publish_data.py."])
    if run(["git", "push", "-u", "origin", branch], check=False) != 0:
        print("push failed. Without write access: `gh repo fork --remote` once, then `git push -u fork " + branch + "` and `gh pr create --fill`.")
        return
    run(["gh", "pr", "create", "--base", "main", "--title", f"Data: {handle} through {TODAY}",
         "--body", f"Status and trade rows from an installed copy's runs, merged into `data/{handle}/`. No account identifiers."], check=False)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("publish"); p.add_argument("--handle", required=True); p.add_argument("--source", required=True); p.add_argument("--pr", action="store_true"); p.set_defaults(fn=cmd_publish)
    s = sub.add_parser("scoreboard"); s.set_defaults(fn=lambda a: scoreboard())
    a = ap.parse_args(); a.fn(a)


if __name__ == "__main__":
    main()
